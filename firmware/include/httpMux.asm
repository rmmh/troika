http_mux_defer: M A 1 O S P
; Generated bytes become immutable when prepare returns, and may be reused
; once copied into retained stream TX. File blocks are owned by each reader.
http_mux_generation:
      R E hs_left E E Z J http_mux_release_generation
      R E fs_opened N E Z J http_mux_release_generation
      R E hs_state E E 1 J http_mux_own_generation E E 3 J http_mux_own_generation
http_mux_release_generation:
      R E hm_generated R F hm_current E E F W hm_generated -1 O S P
http_mux_own_generation:
      R E hm_current W hm_generated E O S P
http_mux_network:
