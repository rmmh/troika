/** Tiny authored bitmap assets for initial PAGE files, not runtime rendering. */
function bitmap(caption: string, drawing: string) {
  const rows = drawing.trim().split('\n');
  if (rows.length !== 12 || rows.some(row => row.length > 18 || !/^[.#]+$/.test(row)) || caption.length < 1 || caption.length > 54) {
    throw new Error(`Invalid catalog bitmap: ${caption}`);
  }
  let pixels = '';
  for (let y = 0; y < 12; y += 2) for (let x = 0; x < 18; x += 2) {
    const bit = (dx: number, dy: number) => rows[y + dy]![x + dx] === '#' ? 1 : 0;
    const mask = bit(0, 0) + 2 * bit(1, 0) + 4 * bit(0, 1) + 8 * bit(1, 1);
    pixels += String.fromCharCode(97 + mask);
  }
  return pixels + caption;
}

