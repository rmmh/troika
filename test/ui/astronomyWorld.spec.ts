import { expect, test } from '@playwright/test';
import { runNativeSoftware } from './softwareBrowser';

test('native solar system loads its archive, edits dates and animates at reversible speeds', async ({page}) => {
  test.setTimeout(240_000);
  const archives: string[] = [];
  page.on('request', request => {if (/de441-.*\.bin/.test(request.url())) archives.push(request.url());});
  const screen = await runNativeSoftware(page,'observatory','/p0318','Solar System / DE441');
  await expect(screen).toContainText('M: Sun-centered system map',{timeout:60_000});
  await expect(screen).toContainText('2000-01-01 12:00:00.000');
  expect(archives).toHaveLength(1);
  expect(archives[0]).toContain('de441-2000-');
  await page.screenshot({path:test.info().outputPath('native-ephemeris-position.png'),fullPage:true});
  const canvas=page.locator('canvas[aria-label="World display keyboard input"]');
  const bitmap=async()=>{await expect.poll(()=>canvas.evaluate((node:HTMLCanvasElement)=>{const c=node.getContext('2d')!;return Array.from(c.getImageData(81,84,1,1).data).join(',');})).toBe('235,186,88,255');};
  await page.keyboard.type('M');
  await bitmap();
  await page.screenshot({path:test.info().outputPath('native-solar-inner.png'),fullPage:true});
  const inner=await canvas.evaluate((node:HTMLCanvasElement)=>node.toDataURL());
  await page.keyboard.type('Z');
  await expect.poll(()=>canvas.evaluate((node:HTMLCanvasElement)=>node.toDataURL())).not.toBe(inner);
  await bitmap();
  await page.screenshot({path:test.info().outputPath('native-solar-outer.png'),fullPage:true});
  await page.keyboard.type('M');
  await expect(screen).toContainText('M: Sun-centered system map');
  await page.keyboard.type('++++');
  await expect(screen).toContainText('365 days/frame');
  await page.keyboard.press('Space');
  await expect(screen).not.toContainText('2000-01-01 12:00:00.000',{timeout:60_000});
  await page.keyboard.press('Space');
  await expect(screen).toContainText('Paused');
  await page.keyboard.type('R');
  await expect(screen).toContainText('-365 days/frame');
  await page.keyboard.type('D');
  await page.keyboard.type('2000-02-30 12:00:00.000');
  await page.keyboard.press('Enter');
  await expect(screen).toContainText('Invalid Gregorian TDB date');
  await page.keyboard.type('D');
  await page.keyboard.type('2000-02-29 12:34:56.789');
  await page.keyboard.press('Enter');
  await expect(screen).toContainText('2000-02-29 12:34:56.789');
  await expect(screen).toContainText('M: Sun-centered system map',{timeout:60_000});
  await page.keyboard.type('M');await bitmap();
  await page.keyboard.type('H');await expect(screen).toContainText('No UTC/UT1 conversion.');
  await page.keyboard.type('M');await bitmap();
  await page.keyboard.type('F');
  await expect(screen).toContainText('Mean radius: 6371.0084 km');
  await expect(screen).toContainText('Facts describe bodies.');
  await page.screenshot({path:test.info().outputPath('native-planet-facts.png'),fullPage:true});
  await page.keyboard.type('H');
  await expect(screen).toContainText('No UTC/UT1 conversion.');
  expect(archives).toHaveLength(1);
  await page.keyboard.press('F1');
  await expect(page.getByRole('status')).toHaveText('Programs');
  await page.keyboard.type('1');
  await expect(screen).toContainText('Welcome to Troika World',{timeout:45_000});
});

test('native animation crosses BCE year zero and archive failures can be retried', async ({page}) => {
  test.setTimeout(240_000);
  const screen=await runNativeSoftware(page,'observatory','/p0318','Solar System / DE441');
  await expect(screen).toContainText('M: Sun-centered system map',{timeout:60_000});
  const date=async(text:string)=>{await page.keyboard.type('D');await page.keyboard.type(text);await page.keyboard.press('Enter');await expect(screen).toContainText(text,{timeout:60_000});await expect(screen).toContainText('M: Sun-centered system map',{timeout:60_000});};
  await date('-0001-12-31 23:00:00.000');
  await page.keyboard.press('Space');
  await expect(screen).toContainText('0000-01-01',{timeout:60_000});
  await page.keyboard.press('Space');
  await expect(screen).toContainText('Paused');
  await expect(screen).toContainText('M: Sun-centered system map',{timeout:60_000});
  await date('-1999-01-01 12:00:00.000');
  await page.screenshot({path:test.info().outputPath('native-ephemeris-bce.png'),fullPage:true});
  let fail=true;
  await page.route('**/de441-3000-*.bin',async route=>{if(fail){fail=false;await route.abort('failed');}else await route.continue();});
  await page.keyboard.type('D');await page.keyboard.type('3000-12-31 23:59:59.999');await page.keyboard.press('Enter');
  await expect(screen).toContainText('Archive download failed',{timeout:60_000});
  await expect(screen).toContainText('3000-12-31 23:59:59.999');
  await page.keyboard.press('Enter');
  await expect(screen).toContainText('M: Sun-centered system map',{timeout:60_000});
  await page.keyboard.press('Space');
  await expect(screen).toContainText('Date limit; reverse to play');
  await expect(screen).toContainText('3000-12-31 23:59:59.999');
  await page.keyboard.press('F1');await expect(page.getByRole('status')).toHaveText('Programs');
  await page.keyboard.type('1');
  await expect(screen).toContainText('Welcome to Troika World',{timeout:45_000});
});
